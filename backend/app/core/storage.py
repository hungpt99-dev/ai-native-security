"""SBOM/artifact storage abstraction.

Artifacts are addressed by opaque storage keys generated by the service layer;
the backend validates every key against the configured root, which prevents
path traversal. Swapping in S3 or another object store only requires a new
``StorageBackend`` implementation.
"""

from __future__ import annotations

import hashlib
import os
import re
import tempfile
from abc import ABC, abstractmethod
from pathlib import Path

from app.core.config import get_settings
from app.core.errors import NotFoundError, ValidationError

_SAFE_KEY_RE = re.compile(r"^[A-Za-z0-9._/\-]+$")


def validate_storage_key(key: str) -> str:
    if not key or not _SAFE_KEY_RE.match(key) or key.startswith("/"):
        raise ValidationError("Invalid storage key")
    if ".." in Path(key).parts:
        raise ValidationError("Invalid storage key")
    return key


class StorageBackend(ABC):
    """Minimal object-store contract used by the SBOM module."""

    @abstractmethod
    def put(self, key: str, data: bytes) -> str:
        """Persist ``data`` and return the stored key."""

    @abstractmethod
    def get(self, key: str) -> bytes: ...

    @abstractmethod
    def exists(self, key: str) -> bool: ...

    @abstractmethod
    def delete(self, key: str) -> None: ...

    @abstractmethod
    def size(self, key: str) -> int: ...

    @staticmethod
    def checksum(data: bytes) -> str:
        return hashlib.sha256(data).hexdigest()


class LocalFileStorage(StorageBackend):
    def __init__(self, root: Path | None = None) -> None:
        self.root = Path(root or get_settings().storage_root).resolve()
        self.root.mkdir(parents=True, exist_ok=True)

    def _path(self, key: str) -> Path:
        validate_storage_key(key)
        candidate = (self.root / key).resolve()
        if self.root not in candidate.parents and candidate != self.root:
            raise ValidationError("Invalid storage key")
        return candidate

    def put(self, key: str, data: bytes) -> str:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        # Atomic write: temp file in the same directory, then rename.
        fd, tmp_name = tempfile.mkstemp(dir=path.parent, prefix=".tmp-")
        try:
            with os.fdopen(fd, "wb") as handle:
                handle.write(data)
                handle.flush()
                os.fsync(handle.fileno())
            os.replace(tmp_name, path)
        except BaseException:  # pragma: no cover - cleanup on failure
            Path(tmp_name).unlink(missing_ok=True)
            raise
        return key

    def get(self, key: str) -> bytes:
        path = self._path(key)
        if not path.is_file():
            raise NotFoundError("Stored artifact not found", details={"key": key})
        return path.read_bytes()

    def exists(self, key: str) -> bool:
        return self._path(key).is_file()

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)

    def size(self, key: str) -> int:
        return self._path(key).stat().st_size


_backend: StorageBackend | None = None


def get_storage() -> StorageBackend:
    global _backend
    if _backend is None:
        settings = get_settings()
        backend = settings.storage_backend.lower()
        if backend != "local":
            raise ValidationError(f"Unsupported storage backend: {backend}")
        _backend = LocalFileStorage()
    return _backend


def reset_storage() -> None:
    """Test helper: drop the cached backend (e.g. after changing the root)."""
    global _backend
    _backend = None
