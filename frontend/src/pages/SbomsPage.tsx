import { useMemo, useState } from "react";
import { Link, useSearchParams } from "react-router-dom";
import { Download, GitCompare } from "lucide-react";
import { Card } from "@/components/ui/card";
import { Label } from "@/components/ui/input";
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from "@/components/ui/select";
import { EmptyState, ErrorState, PageHeader, Pagination } from "@/components/common";
import { TableSkeleton } from "@/components/ui/skeleton";
import { useAssets, useSboms } from "@/hooks/queries";
import { downloadUrl } from "@/lib/api";
import { formatBytes, formatDate, shortSha } from "@/lib/utils";

const reasonLabels: Record<string, string> = {
  FULL_SCAN: "full scan",
  INITIAL: "initial",
  DEPENDENCY_CHANGE: "dependency change",
  WEBHOOK: "webhook",
  MANUAL: "manual",
};

export function SbomsPage() {
  const [searchParams, setSearchParams] = useSearchParams();
  const [page, setPage] = useState(1);
  const [assetId, setAssetId] = useState<string>(searchParams.get("asset") ?? "all");

  const { data: assets } = useAssets({ page: 1, page_size: 100 });
  const params = useMemo(
    () => ({ page, page_size: 20, asset_id: assetId === "all" ? undefined : assetId }),
    [page, assetId],
  );
  const { data, isLoading, error } = useSboms(params);

  return (
    <div>
      <PageHeader
        title="Software bill of materials"
        subtitle="Immutable SBOM snapshots with the commit, composition fingerprint and origin of every generation"
      />

      <div className="mb-4 w-64">
        <Label>Repository</Label>
        <Select
          value={assetId}
          onValueChange={(value) => {
            setPage(1);
            setAssetId(value);
            const next = new URLSearchParams(searchParams);
            if (value === "all") next.delete("asset");
            else next.set("asset", value);
            setSearchParams(next, { replace: true });
          }}
        >
          <SelectTrigger>
            <SelectValue />
          </SelectTrigger>
          <SelectContent>
            <SelectItem value="all">All repositories</SelectItem>
            {(assets?.items ?? []).map((asset) => (
              <SelectItem key={asset.id} value={asset.id}>
                {asset.name}
              </SelectItem>
            ))}
          </SelectContent>
        </Select>
      </div>

      <Card>
        {error ? (
          <ErrorState error={error} />
        ) : isLoading ? (
          <TableSkeleton columns={8} />
        ) : !data || data.items.length === 0 ? (
          <EmptyState
            title="No SBOMs yet"
            description="A snapshot is generated by the first full scan and refreshed automatically when dependency inputs change."
          />
        ) : (
          <>
            <div className="overflow-x-auto">
              <table className="table-base">
                <thead>
                  <tr>
                    <th>SBOM</th>
                    <th>Origin</th>
                    <th>Commit</th>
                    <th>Components</th>
                    <th>Dependency fingerprint</th>
                    <th>Generated</th>
                    <th className="text-right">Actions</th>
                  </tr>
                </thead>
                <tbody>
                  {data.items.map((sbom) => (
                    <tr key={sbom.id}>
                      <td>
                        <Link
                          to={`/sboms/${sbom.id}`}
                          className="font-mono text-xs text-cyan-300 hover:underline"
                        >
                          {sbom.id.slice(0, 8)}
                        </Link>
                        <p className="text-[11px] text-slate-500">
                          {sbom.format.replace("_", " ")}
                          {sbom.spec_version ? ` · ${sbom.spec_version}` : ""}
                        </p>
                      </td>
                      <td className="text-xs text-slate-300">
                        {reasonLabels[sbom.creation_reason ?? ""] ?? sbom.creation_reason ?? "—"}
                        {sbom.generation_status && sbom.generation_status !== "READY" ? (
                          <span className="ml-1 text-amber-300">{sbom.generation_status}</span>
                        ) : null}
                      </td>
                      <td className="font-mono text-xs text-slate-400">{shortSha(sbom.commit_sha)}</td>
                      <td className="tabular-nums">
                        {sbom.package_count}
                        {sbom.direct_package_count !== null ? (
                          <span className="ml-1 text-[11px] text-slate-500">
                            ({sbom.direct_package_count} direct)
                          </span>
                        ) : null}
                      </td>
                      <td className="max-w-[12rem] truncate font-mono text-[11px] text-slate-500">
                        {sbom.dependency_fingerprint ?? "—"}
                      </td>
                      <td className="text-xs text-slate-400">
                        {formatDate(sbom.generated_at ?? sbom.created_at)}
                        <p className="text-[11px] text-slate-600">
                          {formatBytes(sbom.size_bytes)}
                        </p>
                      </td>
                      <td className="text-right">
                        <div className="flex items-center justify-end gap-3">
                          {sbom.previous_snapshot_id ? (
                            <Link
                              to={`/sboms/${sbom.id}/compare`}
                              className="inline-flex items-center gap-1 text-xs text-cyan-400 hover:underline"
                            >
                              <GitCompare className="h-3.5 w-3.5" /> Compare
                            </Link>
                          ) : null}
                          <a
                            className="inline-flex items-center gap-1 text-xs text-cyan-400 hover:underline"
                            href={downloadUrl(`/sboms/${sbom.id}/download`)}
                          >
                            <Download className="h-3.5 w-3.5" /> JSON
                          </a>
                        </div>
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
            <Pagination
              page={data.page}
              pages={data.pages}
              total={data.total}
              pageSize={data.page_size}
              onPageChange={setPage}
            />
          </>
        )}
      </Card>
    </div>
  );
}
