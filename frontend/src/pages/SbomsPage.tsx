import { useMemo, useState } from "react";
import { Link, useSearchParams } from "react-router-dom";
import { Download } from "lucide-react";
import { Card } from "@/components/ui/card";
import { Label } from "@/components/ui/input";
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from "@/components/ui/select";
import { EmptyState, ErrorState, PageHeader, Pagination } from "@/components/common";
import { TableSkeleton } from "@/components/ui/skeleton";
import { useAssets, useSboms } from "@/hooks/queries";
import { downloadUrl } from "@/lib/api";
import { formatBytes, formatDate } from "@/lib/utils";

export function SbomsPage() {
  const [searchParams, setSearchParams] = useSearchParams();
  const [page, setPage] = useState(1);
  const [assetId, setAssetId] = useState<string>(searchParams.get("asset") ?? "all");

  const { data: assets } = useAssets({ page: 1, page_size: 100 });
  const params = useMemo(
    () => ({ page, page_size: 20, asset_id: assetId === "all" ? undefined : assetId }),
    [page, assetId],
  );
  const { data, isLoading, error } = useSboms(params);

  return (
    <div>
      <PageHeader
        title="Software bill of materials"
        subtitle="Every SBOM generated by Syft during a scan, with extracted packages"
      />

      <div className="mb-4 w-64">
        <Label>Repository</Label>
        <Select
          value={assetId}
          onValueChange={(value) => {
            setPage(1);
            setAssetId(value);
            const next = new URLSearchParams(searchParams);
            if (value === "all") next.delete("asset");
            else next.set("asset", value);
            setSearchParams(next, { replace: true });
          }}
        >
          <SelectTrigger>
            <SelectValue />
          </SelectTrigger>
          <SelectContent>
            <SelectItem value="all">All repositories</SelectItem>
            {(assets?.items ?? []).map((asset) => (
              <SelectItem key={asset.id} value={asset.id}>
                {asset.name}
              </SelectItem>
            ))}
          </SelectContent>
        </Select>
      </div>

      <Card>
        {error ? (
          <ErrorState error={error} />
        ) : isLoading ? (
          <TableSkeleton columns={6} />
        ) : !data || data.items.length === 0 ? (
          <EmptyState
            title="No SBOMs yet"
            description="SBOMs are generated automatically by the worker as the first step of every scan."
          />
        ) : (
          <>
            <div className="overflow-x-auto">
              <table className="table-base">
                <thead>
                  <tr>
                    <th>SBOM</th>
                    <th>Format</th>
                    <th>Tool</th>
                    <th>Packages</th>
                    <th>Size</th>
                    <th>Created</th>
                    <th className="text-right">Download</th>
                  </tr>
                </thead>
                <tbody>
                  {data.items.map((sbom) => (
                    <tr key={sbom.id}>
                      <td>
                        <Link to={`/sboms/${sbom.id}`} className="font-mono text-xs text-cyan-300 hover:underline">
                          {sbom.id.slice(0, 8)}
                        </Link>
                      </td>
                      <td className="text-xs text-slate-300">
                        {sbom.format.replace("_", " ")}
                        {sbom.spec_version ? <span className="text-slate-500"> · {sbom.spec_version}</span> : null}
                      </td>
                      <td className="text-xs text-slate-400">
                        {sbom.tool_name} {sbom.tool_version ?? ""}
                      </td>
                      <td className="tabular-nums">{sbom.package_count}</td>
                      <td className="text-xs text-slate-400">{formatBytes(sbom.size_bytes)}</td>
                      <td className="text-xs text-slate-400">{formatDate(sbom.created_at)}</td>
                      <td className="text-right">
                        <a
                          className="inline-flex items-center gap-1 text-xs text-cyan-400 hover:underline"
                          href={downloadUrl(`/sboms/${sbom.id}/download`)}
                        >
                          <Download className="h-3.5 w-3.5" /> JSON
                        </a>
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
            <Pagination
              page={data.page}
              pages={data.pages}
              total={data.total}
              pageSize={data.page_size}
              onPageChange={setPage}
            />
          </>
        )}
      </Card>
    </div>
  );
}
